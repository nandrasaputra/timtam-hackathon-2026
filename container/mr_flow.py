def root_cause(summary: str) -> str:
    match = re.search(
        r"(?:## Hypothesis|\*\*Hypothesis\*\*)\s*\n(.*?)(?:\n## |\n\*\*|\Z)",
        summary,
        re.S,
    )
    text = match.group(1).strip() if match else ""
    return text[:500] if text else "root cause not stated"


def draft_description(summary: str, requester: str) -> str:
    cause = [] if _is_change(summary) else ["Root cause:", root_cause(summary), ""]
    return "\n".join(
        [
            summary.strip()[:2000],
            "",
            *cause,
            "unverified: no lint or compile",
            "generated by bot, needs review",
            f"Requester: {requester}",
        ]
    )


def gitlab_assignee(requester: str) -> str:
    # ponytail: a Lark open_id is not a GitLab user. Only a plain username is passed to glab.
    if requester.startswith("ou_") or not re.fullmatch(r"[A-Za-z0-9._-]+", requester or ""):
        return ""
    return requester


