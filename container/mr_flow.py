"""Confirm a draft MR. The agent never calls this."""

import json
import re

_RC = re.compile(r"\brc/[A-Za-z0-9._-]+")
_NAMED = re.compile(r"\bbranch\s+([A-Za-z0-9._/-]+)", re.IGNORECASE)
_DIFF = re.compile(r"```diff\n(.*?)```", re.DOTALL)


class Pending:
    def __init__(self, ttl: int = 300):
        self.ttl = ttl
        self._items = {}

    def put(self, action_id: str, requester: str, payload: dict, now: float) -> None:
        self._items[action_id] = {
            "requester": requester,
            "payload": payload,
            "exp": now + self.ttl,
        }

    def drop(self, action_id: str) -> None:
        self._items.pop(action_id, None)

    def peek(self, action_id: str, now: float):
        item = self._items.get(action_id)
        if item is None:
            return None
        if now >= item["exp"]:
            self._items.pop(action_id, None)
            return None
        return item["payload"]

    def take(self, action_id: str, clicker: str, now: float):
        item = self._items.get(action_id)
        if item is None:
            return None
        if now >= item["exp"]:
            self._items.pop(action_id, None)
            return None
        if clicker != item["requester"]:
            return None
        self._items.pop(action_id, None)
        return item["payload"]


def _button(label: str, action: str, action_id: str, kind: str) -> dict:
    return {
        "tag": "button",
        "text": {"tag": "plain_text", "content": label},
        "type": kind,
        "value": {"action": action, "action_id": action_id},
    }


def _field(text: str, label: str) -> str:
    match = re.search(rf"\*\*{re.escape(label)}:\*\*\s*(.+)", text)
    return match.group(1).strip() if match else ""


def _is_change(text: str) -> bool:
    return "**Change:**" in text and "Raise MR?" in text


def is_triage(text: str) -> bool:
    change = _is_change(text)
    if not change and "**Issue:**" not in text:
        return False
    if not change and "Raise MR fix?" not in text and not _field(text, "Confidence"):
        return False
    issue = _field(text, "Change" if change else "Issue")
    platform = _field(text, "Platform").lower()
    if not issue or re.search(r"\b(no bug|not specified|not provided|unknown|none|unclear|no details)\b", issue, re.I):
        return False
    if re.search(r"\b(not specified|unknown|none|unclear)\b", platform):
        return False
    if not ("android" in platform or "both" in platform or re.search(r"\bios\b", platform)):
        return False
    if change:
        return True
    confidence = _field(text, "Confidence").lower()
    return confidence.startswith("high") or confidence.startswith("medium")


