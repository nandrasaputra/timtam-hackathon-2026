def projects_from(text: str) -> list[str]:
    match = re.search(r"platform:\**\s*([^\n]+)", text, re.IGNORECASE)
    if not match:
        return []
    line = match.group(1).lower()
    if "both" in line:
        return ["gohost", "ios"]
    found = []
    if "android" in line:
        found.append("gohost")
    if re.search(r"\bios\b", line):
        found.append("ios")
    return found


def branch_from(text: str) -> str:
    match = _RC.search(text)
    if match:
        return match.group(0)
    match = _NAMED.search(text)
    if match:
        return match.group(1).rstrip(".,")
    if re.search(r"\bdevelop\b", text):
        return "develop"
    return ""


def prepare_draft(summary: str, source: str, message_id: str):
    projects = projects_from(summary)
    if not projects:
        return None, "Name Android or iOS before a draft MR."
    branch = branch_from(source) or branch_from(summary) or "develop"
    issue = re.sub(r"[^A-Za-z0-9._-]", "-", message_id).strip("-")[:40] or "issue"
    return {
        "projects": projects,
        "branch": branch,
        "issue": issue,
        "git_branch": f"mobox/{'change' if _is_change(summary) else 'fix'}-{issue}",
        "summary": summary,
    }, None


def confirm_action(store: Pending, action_id: str, choice: str, clicker: str, now: float, draft):
    if choice == "cancel":
        store.drop(action_id)
        return "cancelled"
    item = store.take(action_id, clicker, now)
    if item is None:
        return "expired or not your request"
    return draft(item)


def extract_diff(text: str) -> str:
    match = _DIFF.search(text)
    return match.group(1).strip() if match else ""


def card_fields(data):
    event = getattr(data, "event", None)
    action = getattr(event, "action", None)
    value = getattr(action, "value", None) or {}
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except json.JSONDecodeError:
            value = {}
    if not isinstance(value, dict):
        value = {}
    operator = getattr(event, "operator", None)
    context = getattr(event, "context", None)
    return (
        value.get("action_id", ""),
        value.get("action", ""),
        getattr(operator, "open_id", "") or "",
        getattr(context, "open_message_id", "") or "",
    )
