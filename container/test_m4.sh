#!/usr/bin/env bash
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
BIN="${DIR}/bin/mobox-draft"
fail() { echo "FAIL: $*" >&2; exit 1; }

if "${BIN}" gohost rc/5.81.0_bm_develop om_1 /tmp/nope >/dev/null 2>&1; then
  fail "draft ran without confirm"
fi

tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT
cat > "${tmp}/git" << 'EOF'
#!/bin/sh
printf 'git %s\n' "$*" >> "${CMD_LOG}"
last=""
for arg in "$@"; do last="${arg}"; done
case " $* " in
  *" clone "*) mkdir -p "${last}" ;;
esac
EOF
cat > "${tmp}/glab" << 'EOF'
#!/bin/sh
printf 'glab_cwd %s\n' "$(pwd)" >> "${CMD_LOG}"
printf 'glab %s\n' "$*" >> "${CMD_LOG}"
printf 'https://source.example/mr/9\n'
EOF
chmod +x "${tmp}/git" "${tmp}/glab"
printf '%s\n' '--- a/x' '+++ b/x' > "${tmp}/fix.diff"
printf '%s\n' '**Change:** add the estimate banner event' 'Platform: Android' 'Root cause:' 'null became required' 'unverified: no lint or compile' 'generated by bot, needs review' 'Requester: ou_me' > "${tmp}/desc.txt"
export CMD_LOG="${tmp}/log"
export MOBOX_GIT="${tmp}/git"
export MOBOX_GLAB_BIN="${tmp}/glab"
export GITLAB_HOST="source.golabs.io"
export GITLAB_TOKEN="token"
export GOHOST_PROJECT="mobile/GoHost"
export MOBOX_GIT_EMAIL="dev@gojek.com"
export MOBOX_GIT_NAME="Dev Name"
export MOBOX_WORK="${tmp}"
: > "${CMD_LOG}"

out="$("${BIN}" --confirm gohost rc/5.81.0_bm_develop om_1 "${tmp}/fix.diff" "${tmp}/desc.txt" alice)"
echo "${out}" | grep -q "https://source.example/mr/9" || fail "mr url"
grep -q "clone --depth 1 --branch rc/5.81.0_bm_develop" "${CMD_LOG}" || fail "shallow clone"
grep -q "apply --recount --check" "${CMD_LOG}" || fail "apply check ignores model hunk counts"
grep -q "checkout -b mobox/change-om_1" "${CMD_LOG}" || fail "change branch"
grep -q -- "-s mobox/change-om_1" "${CMD_LOG}" || fail "mr source branch"
grep -q "user.email=dev@gojek.com -c user.name=Dev Name commit" "${CMD_LOG}" || fail "commit identity from env"
grep -q "mr create --draft" "${CMD_LOG}" || fail "draft flag"
grep -q "glab_cwd ${tmp}/mobox-om_1" "${CMD_LOG}" || fail "glab runs in the clone, not the MoBox checkout"
grep -q -- "-t add the estimate banner event" "${CMD_LOG}" || fail "mr title is the change"
if grep -q -- "-t mobox/fix-om_1" "${CMD_LOG}"; then
  fail "mr title is still the branch"
fi
grep -q "unverified: no lint or compile" "${CMD_LOG}" || fail "unverified"
grep -q -- "-a alice" "${CMD_LOG}" || fail "assignee"
if grep -q "mr merge" "${CMD_LOG}"; then
  fail "merge was invoked"
fi
printf '%s\n' '**Issue:** green banner missing' > "${tmp}/bug.txt"
: > "${CMD_LOG}"
"${BIN}" --confirm gohost develop om_2 "${tmp}/fix.diff" "${tmp}/bug.txt" >/dev/null
grep -q "checkout -b mobox/fix-om_2" "${CMD_LOG}" || fail "bug branch stays mobox/fix"
if grep -q "checkout -b mobox/change-om_2" "${CMD_LOG}"; then
  fail "bug branch used the change prefix"
fi
echo ok
